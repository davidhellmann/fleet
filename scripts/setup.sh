#!/usr/bin/env bash
# Set up fleet on this host. Safe to rerun; rerun after adding or removing a shared skill.
#
# 1. Asks once for this host's settings and stores them in fleet.local.json: the folder that holds
#    the repos (root), the host name, whether to ignore the repos' dirs (flat), and the private data
#    repo (data) that holds the repo list (fleet.json) and the usage data. Clones the data repo.
# 2. Clones the repos from fleet.json that are missing on this system, adds their missing worktrees,
#    and writes REPOS.md, the repo list for agents (needs Node 22.18+).
# 3. Links the shared skills (skills/) into ~/.agents/skills and ~/.claude/skills, and installs the
#    missing third-party skills from skills.json with the skills CLI (needs npx).
# 4. Writes the per-host access config for Claude Code and Codex.
# 5. Prints the steps only you can do.
#
# Environment, each skips its question and is stored: FLEET_ROOT=<folder>, FLEET_HOST=<name>,
# FLEET_FLAT=yes|no, FLEET_DATA=<git remote>|none. FLEET_CLONE=yes|no skips the clone question,
# FLEET_SKILLS=yes|no the question to install the third-party skills.
set -euo pipefail

FLEET_DIR="$(cd -P "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)"
FLEET_JSON="$FLEET_DIR/fleet.json" # in the data repo once there is one
LOCAL_JSON="$FLEET_DIR/fleet.local.json"
OLD_CONF="$FLEET_DIR/fleet.conf"
AGENTS_SKILLS="$HOME/.agents/skills"
CLAUDE_SKILLS="$HOME/.claude/skills"
MARKER="generated by fleet/scripts/setup.sh"

say() { printf '%s\n' "$*"; }
warn() { printf 'warning: %s\n' "$*" >&2; }
ask() { [ -t 0 ] && printf '%s' "$1" && read -r answer && return 0; answer=""; }

# --- 1. Host settings ---------------------------------------------------------

# Stored values: fleet.local.json, else the old fleet.conf. The environment wins over both.
root="" host="" flat="" data="" migrate=no
if [ -f "$LOCAL_JSON" ]; then
  # \037 separates the fields, so empty ones survive `read`. data: "" = not asked yet, none = no data repo.
  IFS=$'\037' read -r root host flat data < <(/usr/bin/env python3 - "$LOCAL_JSON" <<'PY'
import json, sys
with open(sys.argv[1]) as f:
    c = json.load(f)
flat = c.get("flat")
data = c["data"] if "data" in c else ""
print(c.get("root", ""), c.get("host", ""), "" if flat is None else ("yes" if flat else "no"), "none" if data is None else data, sep="\037")
PY
  ) || true
elif [ -f "$OLD_CONF" ]; then
  root="$(unset FLEET_REPOS; . "$OLD_CONF"; printf '%s' "${FLEET_REPOS:-}")"
  host="$(unset FLEET_HOST; . "$OLD_CONF"; printf '%s' "${FLEET_HOST:-}")"
  migrate=yes
fi
FLEET_ROOT="${FLEET_ROOT:-$root}"
FLEET_HOST="${FLEET_HOST:-$host}"
FLEET_FLAT="${FLEET_FLAT:-$flat}"
FLEET_DATA="${FLEET_DATA:-$data}"

# Root: the folder that holds the repos.
if [ -z "$FLEET_ROOT" ]; then
  default="$(dirname "$FLEET_DIR")"
  ask "Folder that holds your repos [$default]: "
  FLEET_ROOT="${answer:-$default}"
fi
case "$FLEET_ROOT" in
  "~") FLEET_ROOT="$HOME" ;;
  "~/"*) FLEET_ROOT="$HOME/${FLEET_ROOT#\~/}" ;;
esac
FLEET_ROOT="${FLEET_ROOT%/}"
if [ ! -d "$FLEET_ROOT" ]; then
  warn "$FLEET_ROOT does not exist; create it or fix \"root\" in $LOCAL_JSON"
  exit 1
fi
FLEET_ROOT="$(cd -P "$FLEET_ROOT" && pwd -P)"

# Host name: tags this host's usage stats (stats/<host>/), so it is a folder name.
# Suggested: the short host name, lowercased.
if [ -z "$FLEET_HOST" ]; then
  default="$( (hostname -s 2>/dev/null || uname -n) | tr '[:upper:]' '[:lower:]' \
    | sed -e 's/[^a-z0-9-]/-/g' -e 's/--*/-/g' -e 's/^-//' -e 's/-$//')"
  default="${default:-host}"
  ask "Name of this host, for the usage stats [$default]: "
  FLEET_HOST="${answer:-$default}"
fi
if ! printf '%s' "$FLEET_HOST" | grep -Eqx '[a-z0-9]([a-z0-9-]*[a-z0-9])?'; then
  warn "host name \"$FLEET_HOST\" may only use lowercase letters, digits and inner dashes; fix \"host\" in $LOCAL_JSON"
  exit 1
fi

# Flat: ignore the repos' dirs and keep every repo directly in the root.
if [ -z "$FLEET_FLAT" ]; then
  ask "Ignore the dirs in fleet.json and keep every repo directly in $FLEET_ROOT? [y/N]: "
  case "$answer" in [yY]*) FLEET_FLAT=yes ;; *) FLEET_FLAT=no ;; esac
fi
case "$FLEET_FLAT" in
  yes | no) ;;
  *) warn "FLEET_FLAT must be yes or no, not \"$FLEET_FLAT\""; exit 1 ;;
esac

# Data repo: the private repo holding fleet.json (the repo list) and the usage data, so fleet holds
# nothing personal. Without one, both stay in fleet, ignored by Git.
if [ -z "$FLEET_DATA" ]; then
  ask "Private data repo with your repo list and usage data (Git remote; empty: none, keep them in fleet): "
  FLEET_DATA="${answer:-none}"
fi

# Write the settings, keeping any other keys in the file; untouched when nothing changed.
/usr/bin/env python3 - "$LOCAL_JSON" "$FLEET_ROOT" "$FLEET_HOST" "$FLEET_FLAT" "$FLEET_DATA" <<'PY'
import json, os, sys
path, root, host, flat, data_remote = sys.argv[1:]
data = {}
if os.path.exists(path):
    with open(path) as f:
        data = json.load(f)
data.update(root=root, host=host, flat=flat == "yes", data=None if data_remote == "none" else data_remote)
text = json.dumps(data, indent=2) + "\n"
old = open(path).read() if os.path.exists(path) else None
if text != old:
    with open(path, "w") as f:
        f.write(text)
PY
if [ "$migrate" = yes ] && grep -q "$MARKER" "$OLD_CONF"; then
  rm "$OLD_CONF"
  say "moved fleet.conf to fleet.local.json"
fi
say "root: $FLEET_ROOT$([ "$FLEET_FLAT" = yes ] && printf ' (flat)')"
say "host: $FLEET_HOST"

# The data repo lives directly in the root, named after its remote; cloned now, as it holds the list.
if [ "$FLEET_DATA" != none ]; then
  data_name="${FLEET_DATA%/}"
  data_name="${data_name##*[/:]}"
  DATA_DIR="$FLEET_ROOT/${data_name%.git}"
  if [ ! -d "$DATA_DIR" ]; then
    git clone -q "$FLEET_DATA" "$DATA_DIR" || { warn "could not clone the data repo $FLEET_DATA"; exit 1; }
    say "cloned the data repo to $DATA_DIR"
  fi
  FLEET_JSON="$DATA_DIR/fleet.json"
  say "data: $DATA_DIR"
else
  say "data: none; fleet.json and the usage data stay in fleet"
fi

# --- 2. Repos ----------------------------------------------------------------

# One line per missing item, tab-separated:
#   clone<TAB>path<TAB>remote
#   worktree<TAB>repo path<TAB>worktree path<TAB>branch
# A worktree whose repo is missing is listed too; it is added after the clone.
# Repos whose `os` excludes this system are left out.
case "$(uname -s)" in
  Darwin) this_os=macos ;;
  Linux) this_os=linux ;;
  *) this_os=other ;;
esac
if [ ! -f "$FLEET_JSON" ]; then
  warn "no repo list at $FLEET_JSON; start one from fleet.example.json, then rerun setup"
  no_list=yes
fi
missing="$([ -n "${no_list:-}" ] || /usr/bin/env python3 - "$FLEET_JSON" "$FLEET_ROOT" "$FLEET_FLAT" "$this_os" <<'PY'
import json, os, sys
fleet_json, root, flat, this_os = sys.argv[1:]
with open(fleet_json) as f:
    repos = json.load(f)["repos"]
for repo in repos:
    systems = repo.get("os") or []
    if systems and this_os not in systems:
        continue
    name = repo.get("name", "").strip()
    remote = repo.get("remote", "").strip()
    if not name or not remote:
        print(f"warning: {name or '?'} in fleet.json has no name or remote; skipped", file=sys.stderr)
        continue
    # The repo name is its folder name; a flat host ignores the dir.
    parent = root if flat == "yes" else os.path.join(root, repo.get("dir", "").strip().strip("/"))
    path = os.path.normpath(os.path.join(parent, name))
    if not os.path.exists(path):
        print(f"clone\t{path}\t{remote}")
    for branch in repo.get("worktrees") or []:
        wt = f"{path}-{branch}"
        if not os.path.exists(wt):
            print(f"worktree\t{path}\t{wt}\t{branch}")
PY
)"

if [ -n "${no_list:-}" ]; then
  :
elif [ -z "$missing" ]; then
  say "repos: all present"
else
  say "missing repos and worktrees:"
  printf '%s\n' "$missing" | while IFS=$'\t' read -r kind a b c; do
    case "$kind" in
      clone) say "  clone    ${a#"$FLEET_ROOT"/}" ;;
      worktree) say "  worktree ${b#"$FLEET_ROOT"/} ($c)" ;;
    esac
  done

  clone="${FLEET_CLONE:-}"
  if [ -z "$clone" ]; then
    if [ -t 0 ]; then
      printf 'Clone them now? [Y/n]: '
      read -r answer
      case "$answer" in [nN]*) clone=no ;; *) clone=yes ;; esac
    else
      clone=no
    fi
  fi

  if [ "$clone" = yes ]; then
    while IFS=$'\t' read -r kind a b c <&3; do
      case "$kind" in
        clone)
          mkdir -p "$(dirname "$a")"
          git clone "$b" "$a" || warn "could not clone $b"
          ;;
        worktree)
          if [ ! -e "$a/.git" ]; then
            warn "$a is not a Git repo; skipped worktree $c"
          else
            git -C "$a" worktree add "$b" "$c" || warn "could not add worktree $c of $a"
          fi
          ;;
      esac
    done 3<<< "$missing"
  else
    say "skipped; rerun with FLEET_CLONE=yes to clone"
  fi
fi

# The repo list for agents (REPOS.md, ignored by Git), rendered from fleet.json by the same code as the
# collector's, so it needs Node.
if [ -z "${no_list:-}" ]; then
  if command -v node >/dev/null 2>&1 \
    && node -e 'const [a,b]=process.versions.node.split(".").map(Number);process.exit(a>22||(a===22&&b>=18)?0:1)' 2>/dev/null; then
    node "$FLEET_DIR/scripts/write-repo-list.ts" || warn "could not write REPOS.md"
  else
    warn "REPOS.md not written: needs Node 22.18+; install it, then run node scripts/write-repo-list.ts"
  fi
fi

# --- 3. Shared skills --------------------------------------------------------

# Link every skill in skills/ into $1, and drop links there that point into fleet but are dead.
link_skills() {
  target_dir="$1"
  mkdir -p "$target_dir"

  for link in "$target_dir"/*; do
    [ -L "$link" ] || continue
    case "$(readlink "$link")" in
      "$FLEET_DIR"/*) [ -e "$link" ] || { rm "$link"; say "removed stale link $link"; } ;;
    esac
  done

  for skill in "$FLEET_DIR"/skills/*/; do
    [ -f "$skill/SKILL.md" ] || continue
    skill="${skill%/}"
    dest="$target_dir/$(basename "$skill")"
    if [ -e "$dest" ] && [ ! -L "$dest" ]; then
      warn "$dest exists and is not a link; left as is"
      continue
    fi
    ln -sfn "$skill" "$dest"
  done
  say "skills linked into $target_dir"
}

link_skills "$AGENTS_SKILLS"

# Claude Code reads ~/.claude/skills. Point it at ~/.agents/skills when free, else link into it.
if [ ! -e "$CLAUDE_SKILLS" ] && [ ! -L "$CLAUDE_SKILLS" ]; then
  mkdir -p "$(dirname "$CLAUDE_SKILLS")"
  ln -s "$AGENTS_SKILLS" "$CLAUDE_SKILLS"
  say "linked $CLAUDE_SKILLS -> $AGENTS_SKILLS"
elif [ "$(cd -P "$CLAUDE_SKILLS" && pwd -P)" != "$(cd -P "$AGENTS_SKILLS" && pwd -P)" ]; then
  link_skills "$CLAUDE_SKILLS"
fi

# Third-party skills (skills.json): installed per host with the skills CLI, which records the commit of
# each in ~/.agents/.skill-lock.json. Only missing ones are installed; updates: pnpm skills:update.
if [ -f "$FLEET_DIR/skills.json" ]; then
  # First line: the CLI package. Then one line per source with missing skills: source<TAB>agents<TAB>skills
  wanted="$(/usr/bin/env python3 - "$FLEET_DIR" "$AGENTS_SKILLS" "$CLAUDE_SKILLS" <<'PY'
import json, os, sys
fleet, agents_dir, claude_dir = sys.argv[1:]
with open(os.path.join(fleet, "skills.json")) as f:
    manifest = json.load(f)
own = {n for n in os.listdir(os.path.join(fleet, "skills")) if os.path.isfile(os.path.join(fleet, "skills", n, "SKILL.md"))}
print(manifest["cli"])
agents = " ".join(manifest.get("agents") or [])
for entry in manifest.get("sources", []):
    missing = []
    for name in entry.get("skills", []):
        if name in own:
            print(f"warning: {name} is in skills/ and in skills.json; the one in skills/ is used", file=sys.stderr)
        elif not all(os.path.isfile(os.path.join(d, name, "SKILL.md")) for d in (agents_dir, claude_dir)):
            missing.append(name)
    if missing:
        print(f"{entry['source']}\t{agents}\t{' '.join(missing)}")
PY
  )"
  skills_cli="$(printf '%s\n' "$wanted" | head -n 1)"
  wanted="$(printf '%s\n' "$wanted" | tail -n +2)"

  if [ -z "$wanted" ]; then
    say "third-party skills: all installed"
  else
    say "third-party skills missing (skills.json):"
    printf '%s\n' "$wanted" | while IFS=$'\t' read -r src _ names; do say "  $src: $names"; done

    install="${FLEET_SKILLS:-}"
    if [ -z "$install" ]; then
      if [ -t 0 ]; then
        printf 'Install them now? [Y/n]: '
        read -r answer
        case "$answer" in [nN]*) install=no ;; *) install=yes ;; esac
      else
        install=no
      fi
    fi

    if [ "$install" != yes ]; then
      say "skipped; rerun with FLEET_SKILLS=yes to install"
    elif ! command -v npx >/dev/null 2>&1; then
      warn "npx not found; install Node, then rerun setup to install the third-party skills"
    else
      while IFS=$'\t' read -r src agents names <&3; do
        args=()
        for a in $agents; do args+=(--agent "$a"); done
        for n in $names; do args+=(--skill "$n"); done
        npx -y "$skills_cli" add "$src" --global --yes "${args[@]}" || warn "could not install the skills from $src"
      done 3<<< "$wanted"
    fi
  fi
fi

# --- 4. Access config for Claude Code and Codex ------------------------------

claude_local="$FLEET_DIR/.claude/settings.local.json"
mkdir -p "$(dirname "$claude_local")"
/usr/bin/env python3 - "$claude_local" "$FLEET_ROOT" <<'PY'
import json, os, sys
path, repos = sys.argv[1], sys.argv[2]
data = {}
if os.path.exists(path):
    with open(path) as f:
        data = json.load(f)
dirs = data.setdefault("permissions", {}).setdefault("additionalDirectories", [])
if repos not in dirs:
    dirs.append(repos)
with open(path, "w") as f:
    json.dump(data, f, indent=2)
    f.write("\n")
PY
say "Claude Code: $FLEET_ROOT in .claude/settings.local.json"

codex_conf="$FLEET_DIR/.codex/config.toml"
if [ -f "$codex_conf" ] && ! grep -q "$MARKER" "$codex_conf"; then
  warn "$codex_conf was not written by this script; add $FLEET_ROOT to writable_roots yourself"
else
  mkdir -p "$(dirname "$codex_conf")"
  cat > "$codex_conf" <<EOF
# $MARKER; rerun it instead of editing.
[sandbox_workspace_write]
writable_roots = ["$FLEET_ROOT"]
EOF
  say "Codex: $FLEET_ROOT in .codex/config.toml"
fi

# --- 5. Steps only you can do ------------------------------------------------

cat <<EOF

Done. Left for you:
- Codex: mark $FLEET_DIR as a trusted project, or it ignores .codex/config.toml.
- Amp orbs: import the shared skills into your Amp personal skills (README.md).
EOF
